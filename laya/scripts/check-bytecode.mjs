import fs from 'node:fs';
import vm from 'node:vm';
import {spawn} from 'node:child_process';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export const MAX_BYTECODE_SIZE = 60 * 1024;
const script = fileURLToPath(import.meta.url);

// Compile only: never initialize the library or execute generated native code.
if (process.argv[2] === '--worker') {
    const source = fs.readFileSync(process.argv[3], 'utf8');
    fs.writeSync(1, '\n__RECAST_BYTECODE_BEGIN__\n');
    new vm.Script(source, {filename: process.argv[3]});
    fs.writeSync(1, `\n__RECAST_BYTECODE_END__ V8=${process.versions.v8}\n`);
}

export async function inspectBytecode(file, {runtime = process.env.JS_BYTECODE_NODE || process.execPath,
    maxBytecodeSize = MAX_BYTECODE_SIZE} = {}) {
    return new Promise((done, reject) => {
        const child = spawn(runtime, ['--no-lazy', '--print-bytecode', '--print-bytecode-filter=*',
            script, '--worker', resolve(file)], {
            env: {...process.env, ELECTRON_RUN_AS_NODE: '1'}, stdio: ['ignore', 'pipe', 'pipe']
        });
        let pending = '', active = false, ended = false, name = '', stderr = '', v8;
        const functions = [];
        const timeout = setTimeout(() => child.kill(), 120_000);
        child.on('error', reject);
        child.stderr.on('data', chunk => { stderr = (stderr + chunk).slice(-8192); });
        // Stream the disassembly; retain sizes only, rather than megabytes of instructions.
        child.stdout.on('data', chunk => {
            pending += chunk;
            let index;
            while ((index = pending.indexOf('\n')) >= 0) {
                const line = pending.slice(0, index);
                pending = pending.slice(index + 1);
                if (line === '__RECAST_BYTECODE_BEGIN__') { active = true; continue; }
                const end = line.match(/^__RECAST_BYTECODE_END__ V8=(.+)$/);
                if (end) { active = false; ended = true; v8 = end[1]; continue; }
                if (!active) continue;
                const header = line.match(/^\[generated bytecode for function: (.*?) \(/);
                if (header) name = header[1] || '<anonymous>';
                const size = line.match(/^Bytecode length: (\d+)/);
                if (size) functions.push({name, bytes: Number(size[1])});
            }
        });
        child.on('close', code => {
            clearTimeout(timeout);
            if (code !== 0 || !ended || functions.length === 0)
                return reject(new Error(`Bytecode inspection failed (exit ${code}): ${stderr}`));
            functions.sort((a, b) => b.bytes - a.bytes);
            done({v8, maxBytecodeSize, functions, oversized: functions.filter(f => f.bytes > maxBytecodeSize)});
        });
    });
}

if (process.argv[1] && resolve(process.argv[1]) === script && process.argv[2] !== '--worker') {
    try {
        if (!process.argv[2]) throw new Error('Usage: node scripts/check-bytecode.mjs <recast-navigation.js>');
        const report = await inspectBytecode(process.argv[2]);
        console.log(`V8 ${report.v8}: ${report.functions.length} functions; limit ${report.maxBytecodeSize} bytes`);
        for (const f of report.functions.slice(0, 5)) console.log(`${f.name}: ${f.bytes} bytes`);
        if (report.oversized.length) throw new Error(`${report.oversized.length} functions exceed the V8 bytecode budget`);
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}
